"""Re-execute the published notebook and export a GitHub-readable Markdown copy."""
import argparse
import json
import os
import sys
from pathlib import Path

import nbformat
from nbclient import NotebookClient
from jupyter_client import KernelManager
from jupyter_client.kernelspec import KernelSpecManager

ROOT = Path(__file__).resolve().parents[1]
SCRATCH = ROOT / "artifacts/report_runtime"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--language", choices=("en", "zh-CN"), default="en")
    args = parser.parse_args()
    base = ROOT if args.language == "en" else ROOT / "docs/zh-CN"
    report = base / "reports/long_input_serving"

    for name, folder in (("IPYTHONDIR", "ipython"), ("MPLCONFIGDIR", "matplotlib"), ("JUPYTER_RUNTIME_DIR", "runtime")):
        directory = SCRATCH / folder
        directory.mkdir(parents=True, exist_ok=True)
        os.environ[name] = str(directory)
    kernel = SCRATCH / "kernels/python3"
    kernel.mkdir(parents=True, exist_ok=True)
    (kernel / "kernel.json").write_text(json.dumps({"argv": [sys.executable, "-m", "ipykernel_launcher", "-f", "{connection_file}"], "display_name": "Python 3", "language": "python"}), encoding="utf-8")
    manager = KernelManager(kernel_name="python3", kernel_spec_manager=KernelSpecManager(kernel_dirs=[str(kernel.parent)]))
    path = report / "mixed_scheduling_report.ipynb"
    notebook = nbformat.read(path, as_version=4)
    NotebookClient(notebook, km=manager, timeout=180, resources={"metadata": {"path": str(ROOT)}}).execute()
    nbformat.validate(notebook)
    nbformat.write(notebook, path)
    figures = iter(("01_tradeoff", "02_paired_benefits", "03_generation_stalls", "04_latency_decomposition", "05_backlog"))
    sections, images = [], 0
    for cell in notebook.cells:
        if cell.cell_type == "markdown":
            sections.append(cell.source.replace("/mixed_scheduling_report.ipynb)", "/README.md)"))
            continue
        assert cell.execution_count is not None
        for output in cell.outputs:
            assert output.output_type != "error"
            data = output.get("data", {})
            if "text/markdown" in data:
                sections.append(data["text/markdown"])
            if "image/png" in data:
                name = next(figures)
                sections.append(f"![{name}](figures/{name}.png)")
                images += 1
    assert images == 5
    sections.insert(0, "<!-- Generated by tools/render_serving_report.py from the executed notebook. -->")
    (report / "README.md").write_text("\n\n".join(sections) + "\n", encoding="utf-8", newline="\n")
    print("Executed notebook and exported Markdown; 5 figures; no model loaded.")


if __name__ == "__main__":
    main()
